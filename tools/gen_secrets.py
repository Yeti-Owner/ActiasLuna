"""Build the firmware secrets header and the phone-page TLS cert from config/network.json."""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "network.json"
HEADER = ROOT / "firmware" / "luna_node" / "main" / "luna_secrets.h"
CERTS = ROOT / "config" / "certs"


def quote_c(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def validate(cfg: dict) -> list:
    problems = []
    ssid, pw = cfg.get("ssid", ""), cfg.get("password", "")
    if not 1 <= len(ssid.encode()) <= 32:
        problems.append("ssid must be 1..32 bytes")
    # Firmware main.c writes the SSID unescaped into its JSON "hi" packet.
    if any(c in '"\\' or ord(c) < 32 for c in ssid):
        problems.append('ssid must not contain " or \\ or control characters')
    if not (8 <= len(pw) <= 63 and pw.isascii()):
        problems.append("password must be 8..63 ASCII characters (WPA2)")
    if cfg.get("channel") not in range(1, 14):
        problems.append("channel must be 1..13 (2.4 GHz)")
    if cfg.get("max_stations") not in range(1, 16):
        problems.append("max_stations must be 1..15 (ESP32-S3 soft-AP limit: boards + laptop + phones)")
    if cfg.get("node_port") not in range(1024, 65536):
        problems.append("node_port must be 1024..65535")
    return problems


def make_cert(ip: str):
    # The phone page must be a secure context or browsers hide motion/compass sensors. The cert is created once and
    # reused so phones that already accepted the warning keep trusting it. iOS refuses server certs valid > 825 days.
    cert_path, key_path = CERTS / "servercert.pem", CERTS / "prvtkey.pem"
    if cert_path.exists() and key_path.exists():
        return
    try:
        import datetime
        import ipaddress
        from cryptography import x509
        from cryptography.hazmat.primitives import hashes, serialization
        from cryptography.hazmat.primitives.asymmetric import ec
        from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID
    except ImportError:
        print("`cryptography` missing (pip install cryptography): the phone page will run over http without sensors")
        return
    key = ec.generate_private_key(ec.SECP256R1())
    subject = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, ip)])
    start = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(days=1)
    builder = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(subject)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(start)
        .not_valid_after(start + datetime.timedelta(days=800))
        .add_extension(x509.SubjectAlternativeName([x509.IPAddress(ipaddress.ip_address(ip))]), critical=False)
        .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
    )
    cert = builder.sign(key, hashes.SHA256())
    CERTS.mkdir(parents=True, exist_ok=True)
    cert_path.write_bytes(cert.public_bytes(serialization.Encoding.PEM))
    key_path.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL,
                                           serialization.NoEncryption()))
    print(f"created {cert_path.relative_to(ROOT)} (self-signed for {ip})")


def main():
    if not CONFIG.exists():
        sys.exit("config/network.json not found: copy config/network.example.json and set a password")
    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    problems = validate(cfg)
    if problems:
        sys.exit("config/network.json: " + "; ".join(problems))
    lines = [
        "// Generated by tools/gen_secrets.py from config/network.json. Do not edit by hand.",
        "#pragma once",
        f"#define LUNA_SSID {quote_c(cfg['ssid'])}",
        f"#define LUNA_PASS {quote_c(cfg['password'])}",
        f"#define LUNA_CHANNEL {int(cfg['channel'])}",
        f"#define LUNA_MAX_STA {int(cfg['max_stations'])}",
        f"#define LUNA_NODE_PORT {int(cfg['node_port'])}",
    ]
    text = "\n".join(lines) + "\n"
    make_cert(cfg.get("ap_ip", "192.168.4.1"))
    if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
        HEADER.write_text(text, encoding="utf-8")
        print(f"updated {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
